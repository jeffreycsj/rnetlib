//! Cargo must produce a consumable header without rewriting the checked-in SDK.

#[test]
fn cargo_emits_the_current_c_header() {
    let output = env!("OUT_DIR");
    let header = std::fs::read_to_string(std::path::Path::new(output).join("rnet.h"))
        .expect("generated rnet.h must be readable");
    assert!(header.contains("Generated by cbindgen"));
    for symbol in include_str!("../../../scripts/expected-exports.txt").lines() {
        assert!(header.contains(&format!("{symbol}(")), "missing {symbol}");
    }
    assert!(header.contains("rnet_game_event_t"));
    assert!(header.contains("RNET_ABI_VERSION"));
}
