#ifndef RNET_RUNTIME_HPP
#define RNET_RUNTIME_HPP

#include "rnet/keypair.hpp"

#include <utility>

namespace rnet {

/// Transport selected once when opening an endpoint; never passed on each send.
enum class Transport : uint32_t {
  Tcp = RNET_TRANSPORT_TCP, ///< Reliable ordered stream transport with library message framing.
  Udp = RNET_TRANSPORT_UDP, ///< Unreliable message transport; no retransmission or delivery guarantee.
  Kcp = RNET_TRANSPORT_KCP ///< Reliable ordered KCP delivery over UDP.
};

/// Authenticated listener options; the runtime copies key/address configuration on listen.
struct ServerOptions {
  Transport transport = Transport::Tcp; ///< Fixed TCP/UDP/KCP transport for this listener.
  std::string host = "127.0.0.1"; ///< Numeric bind IP without brackets, scheme or port; DNS is not accepted.
  uint16_t port = 0; ///< Local bind port; zero requests an OS-assigned port.
  Keypair keypair; ///< Server identity, generated by default; reuse a stable key when clients pin it.
  SecurityMode initial_security = SecurityMode::Encrypted; ///< Business-data mode; Plaintext requires runtime opt-in.
};

/// Outbound transport endpoint options; runtime-scoped trust and server policy supply security.
struct ClientOptions {
  Transport transport = Transport::Tcp; ///< Fixed transport; must match the server.
  std::string host = "127.0.0.1"; ///< DNS name or numeric IP without URL scheme/path or embedded port.
  uint16_t port = 0; ///< Remote service port; must be nonzero.
  std::string join_payload; ///< Opaque protected join bytes; copied by connect and surfaced for server authorization.
};

/// Move-only authenticated transport runtime; game users normally want GameRuntime.
/// Methods throw Error with native status/detail; allocations may throw bad_alloc.
/// Handles are object-local. Use one poll consumer and synchronize move/close/destruction
/// with all calls. Logger callback/context must outlive destruction and must not stop it.
/// Destructor cleanup is best-effort; explicit close reports lifecycle/cleanup failures.
class Runtime {
 public:
  /// Secure default server-capable runtime; does not bind or connect.
  Runtime() {
    check_abi();
    rnet_config_t config{};
    check(rnet_config_init(&config));
    check(rnet_runtime_create(&config, nullptr, &handle_));
  }

  /// Copies initialized/customized rnet_config_t; callback/context retain caller-owned lifetime.
  explicit Runtime(const rnet_config_t &config) {
    check_abi();
    check(rnet_runtime_create(&config, nullptr, &handle_));
  }

  /* Client identity and trust are runtime-scoped; connect() never selects a
   * plaintext/encrypted branch. */

  /// Copies client identity and exact server public-key pin; also permits local listen.
  Runtime(const rnet_config_t &config, const Keypair &client_key,
          const std::array<uint8_t, 32> &expected_server_key) {
    check_abi();
    rnet_client_security_t security = {};
    security.struct_size = sizeof(security);
    security.abi_version = RNET_ABI_VERSION;
    security.local_private_key.ptr = client_key.private_key();
    security.local_private_key.len = 32;
    security.expected_server_public_key.ptr = expected_server_key.data();
    security.expected_server_public_key.len = expected_server_key.size();
    check(rnet_runtime_create(&config, &security, &handle_));
  }

  /// Unique ownership: runtime resources cannot be copied.
  Runtime(const Runtime &) = delete;
  /// Unique ownership: transfer with move instead.
  Runtime &operator=(const Runtime &) = delete;

  /// Transfers ownership and empties other; externally serialize both objects' lifetimes.
  Runtime(Runtime &&other) noexcept : handle_(other.handle_) {
    other.handle_ = 0;
  }

  /// Best-effort closes old resources before transfer; explicit close exposes cleanup errors.
  Runtime &operator=(Runtime &&other) noexcept {
    if (this != &other) {
      reset();
      handle_ = other.handle_;
      other.handle_ = 0;
    }
    return *this;
  }

  /// Best-effort stop/destroy without throwing; use close for checked shutdown.
  ~Runtime() { reset(); }

  /// Binds options' numeric address/transport and returns listener; authorize incoming AUTH_REQUEST.
  rnet_endpoint_t listen(const ServerOptions &options) {
    rnet_server_config_t config = {};
    config.struct_size = sizeof(config);
    config.abi_version = RNET_ABI_VERSION;
    config.transport = static_cast<uint32_t>(options.transport);
    config.initial_security = static_cast<uint32_t>(options.initial_security);
    config.bind_host.ptr = reinterpret_cast<const uint8_t *>(options.host.data());
    config.bind_host.len = options.host.size();
    config.bind_port = options.port;
    config.local_private_key.ptr = options.keypair.private_key();
    config.local_private_key.len = 32;
    rnet_endpoint_t endpoint = 0;
    check(rnet_server_listen(handle_, &config, &endpoint));
    return endpoint;
  }

  /// Starts join and returns endpoint; requires constructor trust. DNS may wait; poll for SESSION_OPENED.
  rnet_endpoint_t connect(const ClientOptions &options) {
    rnet_client_config_t config = {};
    config.struct_size = sizeof(config);
    config.abi_version = RNET_ABI_VERSION;
    config.transport = static_cast<uint32_t>(options.transport);
    config.remote_host.ptr = reinterpret_cast<const uint8_t *>(options.host.data());
    config.remote_host.len = options.host.size();
    config.remote_port = options.port;
    config.join_payload.ptr =
        reinterpret_cast<const uint8_t *>(options.join_payload.data());
    config.join_payload.len = options.join_payload.size();
    rnet_endpoint_t endpoint = 0;
    check(rnet_client_connect(handle_, &config, &endpoint));
    return endpoint;
  }

  /// Answers pending server AUTH_REQUEST; success queues decision, not readiness for sending.
  void auth_decide(rnet_session_t session, bool accept) const {
    check(rnet_session_auth_decide(handle_, session, accept ? 1u : 0u));
  }

  /// Server requests business mode; Plaintext requires opt-in. SECURITY_CHANGED confirms local commit.
  /// Requesting the already active mode can succeed without another event.
  void set_security(rnet_session_t session, SecurityMode mode) const {
    check(rnet_session_security_set(handle_, session,
                                    static_cast<uint32_t>(mode)));
  }

  /// Server requests rotation; wait for SECURITY_CHANGED/REKEY, not this call, to observe completion.
  void rekey(rnet_session_t session) const {
    check(rnet_session_rekey(handle_, session));
  }

  /// Returns live endpoint's bound port (including ephemeral port); invalid handles throw.
  uint16_t local_port(rnet_endpoint_t endpoint) const {
    uint16_t port = 0;
    check(rnet_endpoint_local_port(handle_, endpoint, &port));
    return port;
  }

  /// Copies binary-safe payload to an open session; success is admission, not delivery.
  /// Empty is valid; oversize, not-open and backpressure throw Error.
  void send(rnet_session_t session,
            const std::string &payload) const {
    send(session, payload.data(), payload.size());
  }

  /// Copies payload_size bytes; payload may be null only for zero size. No msg_type/transport argument.
  void send(rnet_session_t session, const void *payload,
            size_t payload_size) const {
    rnet_slice_t bytes;
    bytes.ptr = static_cast<const uint8_t *>(payload);
    bytes.len = payload_size;
    check(rnet_session_send(handle_, session, bytes));
  }

  /// Copies payload with optional peer-visible correlation ID; normal send limits/backpressure apply.
  void send_with_options(rnet_session_t session,
                         const std::string &payload,
                         const SendOptions &options) const {
    rnet_send_options_t raw = {};
    raw.struct_size = sizeof(raw);
    raw.abi_version = RNET_ABI_VERSION;
    raw.correlation_id = options.correlation_id;
    rnet_slice_t bytes = {
        reinterpret_cast<const uint8_t *>(payload.data()), payload.size()};
    check(rnet_session_send_ex(handle_, session, bytes, &raw));
  }



  /// Returns up to capacity owned events; releases native tokens even if copying throws.
  /// timeout_ms limits idle wait, not total call duration. Zero capacity validates/logs only.
  /// Allocation failure consumes exported events; callers cannot replay them by retrying.
  std::vector<Event> poll(size_t capacity, uint32_t timeout_ms) const {
    std::vector<rnet_event_t> raw(capacity);
    size_t count = 0;
    const int32_t status = rnet_poll_events(handle_, raw.empty() ? NULL : raw.data(),
                                           raw.size(), timeout_ms, &count);
    // Own the exported batch before error conversion or payload copies allocate.
    struct ReleaseBatch {
      rnet_runtime_t runtime;
      std::vector<rnet_event_t> &events;
      size_t count;
      ~ReleaseBatch() {
        for (size_t i = 0; i < count; ++i) {
          if (events[i].buffer_token != 0)
            (void)rnet_buffer_release(runtime, events[i].buffer_token);
        }
      }
    } release{handle_, raw, count};
    check(status);
    std::vector<Event> result;
    result.reserve(count);
    for (size_t index = 0; index < count; ++index) {
      auto &source = raw[index];
      Event event;
      event.type = source.event_type;
      event.endpoint = source.endpoint;
      event.session = source.session;
      event.correlation_id = source.correlation_id;
      event.status = source.status;
      if (source.data_len != 0) {
        event.data.assign(source.data, source.data + source.data_len);
      }
      // Release copied payloads promptly; the guard owns only the remaining tokens.
      if (source.buffer_token != 0) {
        check(rnet_buffer_release(handle_, source.buffer_token));
        source.buffer_token = 0;
      }
      result.push_back(std::move(event));
    }
    return result;
  }

  /// Closes peer with local RNET_OK/RNET_E_* reason; does not close its listener.
  void close_session(rnet_session_t session,
                     int32_t reason = RNET_E_CANCELLED) const {
    check(rnet_session_close(handle_, session, reason));
  }

  /// Closes endpoint and owned sessions; runtime remains usable.
  void close_endpoint(rnet_endpoint_t endpoint) const {
    check(rnet_endpoint_close(handle_, endpoint));
  }

  /// Cumulative transport counters/live gauges; no reset or globally atomic observation.
  Metrics metrics() const {
    rnet_metrics_t raw = {};
    check(rnet_metrics_snapshot(handle_, &raw));
    Metrics result;
    result.frames_received = raw.frames_received;
    result.frames_sent = raw.frames_sent;
    result.bytes_received = raw.bytes_received;
    result.bytes_sent = raw.bytes_sent;
    result.events_dropped = raw.events_dropped;
    result.send_would_block = raw.send_would_block;
    result.protocol_errors = raw.protocol_errors;
    result.lifecycle_events_rejected = raw.lifecycle_events_rejected;
    result.admission_rejected = raw.admission_rejected;
    result.queued_send_bytes = raw.queued_send_bytes;
    result.peak_queued_send_bytes = raw.peak_queued_send_bytes;
    result.queued_event_bytes = raw.queued_event_bytes;
    result.current_endpoints = raw.current_endpoints;
    result.current_sessions = raw.current_sessions;
    result.established_sessions = raw.established_sessions;
    result.pending_handshakes = raw.pending_handshakes;
    result.peak_pending_handshakes = raw.peak_pending_handshakes;
    std::copy(raw.admission_rejected_by_reason,
              raw.admission_rejected_by_reason + 8,
              result.admission_rejected_by_reason.begin());
    std::copy(raw.session_closed_by_reason,
              raw.session_closed_by_reason + 19,
              result.session_closed_by_reason.begin());
    result.logs_dropped = raw.logs_dropped;
    result.logger_panics = raw.logger_panics;
    return result;
  }

  /// Histogram estimates in microseconds; drain_window=false reads cumulative samples.
  /// true rotates window buckets; sample_count=0 means unavailable, not zero latency.
  std::vector<LatencyMetric> latency_metrics(bool drain_window = false) const {
    size_t count = 0;
    check(rnet_latency_snapshot(handle_, NULL, 0, &count,
                                   drain_window ? 1U : 0U));
    std::vector<rnet_latency_metric_t> raw(count);
    check(rnet_latency_snapshot(handle_, raw.empty() ? NULL : raw.data(),
                                   raw.size(), &count,
                                   drain_window ? 1U : 0U));
    std::vector<LatencyMetric> result;
    result.reserve(count);
    for (size_t index = 0; index < count; ++index) {
      LatencyMetric metric;
      metric.kind = raw[index].kind;
      metric.sample_count = raw[index].sample_count;
      metric.p50_us = raw[index].p50_us;
      metric.p90_us = raw[index].p90_us;
      metric.p95_us = raw[index].p95_us;
      metric.p99_us = raw[index].p99_us;
      metric.p999_us = raw[index].p999_us;
      metric.max_us = raw[index].max_us;
      result.push_back(metric);
    }
    return result;
  }

  /// Changes poll-driven summary interval in milliseconds; zero disables.
  void set_metrics_log_interval(uint64_t interval_ms) const {
    check(rnet_metrics_log_interval_set(handle_, interval_ms));
  }

  /// Stops I/O with drain_timeout_ms send budget (zero=no drain); keeps handle for final poll.
  /// On WOULD_BLOCK poll and retry; forbidden from logger callbacks.
  void stop(uint32_t drain_timeout_ms = 0) {
    if (handle_ != 0) {
      check(rnet_runtime_stop(handle_, drain_timeout_ms));
    }
  }

  /// Checked stop(0)/destroy. Failed cleanup keeps handle for retry; empty object is a no-op.
  void close() {
    if (handle_ == 0) {
      return;
    }
    stop();
    check(rnet_runtime_destroy(handle_));
    handle_ = 0;
  }

 private:
  void reset() noexcept {
    if (handle_ == 0) {
      return;
    }
    (void)rnet_runtime_stop(handle_, 0);
    (void)rnet_runtime_destroy(handle_);
    handle_ = 0;
  }

  rnet_runtime_t handle_ = 0;
};

}  // namespace rnet

#endif
